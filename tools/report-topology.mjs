#!/usr/bin/env node
// Writes the per-glyph identity/topology report for A/B/G/R/S (Ticket 0.7A-T03).
// Usage: node tools/report-topology.mjs [--check]

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { loadRegistry } from '../src/glyph/load-node.js';
import { topologyReport } from '../src/glyph/semantic-overlay.js';

const authoredChars = (registry) => registry.list().filter((g) => g.semanticGraph.components.length).map((g) => g.character);

export const REPORT_PATH = 'docs/reports/T03_TOPOLOGY_REPORT.md';

export function renderReport(registry) {
  const lines = [
    `# Identity and Topology Report (${authoredChars(registry).join('/')})`,
    '',
    '_Generated by `node tools/report-topology.mjs`. Do not edit by hand._',
    '',
    `Registry: ${registry.meta.source} · authored ${(registry.meta.authored ?? []).join(', ') || '—'} · overlay ${registry.meta.semanticOverlay} · importer ${registry.meta.importer}`,
    '',
    'Declarations only. Nothing in this report is a geometric measurement of topology or a review result; ',
    'constraints stay `declared-unverified` until the T04 validator runs and humans review proof sheets.',
    '',
    '| Glyph | Maturity | Counters | Aperture | Components (mapped / total) | Open findings |',
    '|---|---|---|---|---|---|',
  ];
  const reports = authoredChars(registry).map((ch) => topologyReport(registry.getByChar(ch)));
  for (const r of reports) {
    const open = r.findings.filter((f) => f.severity !== 'info').map((f) => `\`${f.code}\``).join(', ') || '—';
    lines.push(`| ${r.glyphId} | ${r.maturity} | ${r.negativeSpace.counters.length} (${r.negativeSpace.counterStatus}) | ${r.negativeSpace.apertures.status} | ${r.components.mapped.length} / ${r.components.total} | ${open} |`);
  }
  for (const r of reports) {
    const g = registry.get(r.glyphId);
    lines.push('', `## ${r.glyphId}`, '');
    lines.push('| Component | Role | Mapping | Geometry / candidates |', '|---|---|---|---|');
    for (const c of g.semanticGraph.components) {
      const refs = c.mappingStatus === 'mapped' ? c.geometryRefs : c.candidateGeometryRefs;
      const short = refs.map((x) => x.replace(`glyph.${g.character}.contour.`, '')).join(', ') || '—';
      lines.push(`| ${c.label} | ${c.role} | ${c.mappingStatus} | ${short} |`);
    }
    lines.push('', `Topology signature (declared): ${JSON.stringify(r.signature)}`);
    lines.push('', 'Identity checks pending the validator: ' + g.semanticGraph.identityProfile.checks.map((c) => `\`${c.name}\``).join(', '));
    if (g.semanticGraph.apertureInterpretation) {
      const ai = g.semanticGraph.apertureInterpretation;
      lines.push('', `**Aperture: ${ai.status}.** ${ai.intendedIdentity}`, '', 'Blockers:');
      for (const b of ai.blockers) lines.push(`- ${b}`);
      lines.push('', 'Observations (unreviewed):');
      for (const o of ai.observations) lines.push(`- ${o}`);
    }
    lines.push('', 'Findings:');
    for (const f of r.findings) lines.push(`- \`${f.code}\` (${f.severity}): ${f.message}`);
  }
  return lines.join('\n') + '\n';
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = renderReport(loadRegistry());
  if (process.argv.includes('--check')) {
    if (readFileSync(REPORT_PATH, 'utf8') !== text) { console.error(`${REPORT_PATH} is stale`); process.exit(1); }
    console.log('Report up to date.');
  } else {
    writeFileSync(REPORT_PATH, text);
    console.log(`Wrote ${REPORT_PATH}`);
  }
}
