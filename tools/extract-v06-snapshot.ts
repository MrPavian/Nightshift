/**
 * Extracts the verbatim glyph path strings from the Build 0.6 reference prototype
 * and writes them, with a SHA-256 of the source file, to src/core/legacy/v06-snapshot.ts.
 *
 * The prototype is read-only. Extraction fails loudly if the source layout differs from
 * what this parser expects; it never guesses or repairs.
 *
 * Usage: npm run extract:v06
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { execSync } from 'node:child_process';
import { extractV06 } from './v06-extract.ts';

const SOURCE = 'prototypes/nightshift_art_engine_v06.html';
const TARGET = 'src/core/legacy/v06-snapshot.ts';

const html = readFileSync(SOURCE, 'utf8');
const snap = extractV06(html);
let commit = 'unknown';
try {
  commit = execSync(`git log -1 --format=%H -- ${SOURCE}`, { encoding: 'utf8' }).trim() || 'unknown';
} catch {
  /* not a git checkout */
}

const out = `// GENERATED by tools/extract-v06-snapshot.ts — do not edit by hand.
// Verbatim glyph path strings from the Build 0.6 reference prototype.
export const V06_SNAPSHOT = ${JSON.stringify({ ...snap, sourceCommit: commit }, null, 2)} as const;
`;
writeFileSync(TARGET, out);
console.log(`Wrote ${TARGET}: ${Object.keys(snap.custom).length} custom, ${Object.keys(snap.provisional).length} provisional, sha256 ${snap.sourceSha256}`);
