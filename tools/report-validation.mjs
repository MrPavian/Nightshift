#!/usr/bin/env node
// Writes the geometry validation report for all 26 glyphs (Ticket 0.7A-T04).
// Usage: node tools/report-validation.mjs [--check]

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { loadRegistry } from '../src/glyph/load-node.js';
import { validateGlyphGeometry, VALIDATOR_VERSION } from '../src/glyph/validate-geometry.js';

export const VALIDATION_REPORT_PATH = 'docs/reports/T04_VALIDATION_REPORT.md';
const PROFILE_PATH = 'data/validator-profiles/legacy-v06.v1.json';

const short = (id) => id.replace(/^glyph\.[A-Z]\.contour\./, '');

export function renderValidationReport(registry, profile) {
  const reports = registry.list().map((g) => validateGlyphGeometry(g, profile));
  const L = [
    '# 0.7A-T04 — Geometry Validation Report',
    '',
    '_Generated by `node tools/report-validation.mjs`. Do not edit by hand._',
    '',
    `Validator ${VALIDATOR_VERSION} · profile ${profile.profileId}@${profile.version} · registry ${registry.meta.source}`,
    '',
    'Automated validation is not human approval. Clearance values are measurements in legacy units; no threshold is calibrated, ',
    'so nothing is passed or failed on clearance. `side` says whether the measured gap is filled material (wall/stroke) or unfilled space.',
    '',
    '## Summary (A–Z)',
    '',
    '| Glyph | Maturity | Hard checks | Components | Errors | Warnings |',
    '|---|---|---|---|---|---|',
  ];
  for (const r of reports) {
    const g = registry.get(r.glyphId);
    const errs = [...new Set(r.diagnostics.filter((d) => d.severity === 'error').map((d) => `\`${d.code}\``))].join(', ') || '—';
    const warns = [...new Set(r.diagnostics.filter((d) => d.severity === 'warning').map((d) => `\`${d.code}\``))].join(', ') || '—';
    L.push(`| ${g.character} | ${g.maturity} | ${r.hardChecksPassed ? 'pass' : '**fail**'} | ${r.topology.connectedComponents ?? '?'} | ${errs} | ${warns} |`);
  }
  for (const r of reports.filter((x) => ['A', 'B', 'G', 'R', 'S'].includes(x.glyphId.slice(-1)))) {
    L.push('', `## ${r.glyphId}`, '');
    L.push('| Stage | Status |', '|---|---|');
    for (const s of r.stages) L.push(`| ${s.stage} | ${s.status}${s.note ? ` — ${s.note}` : ''} |`);
    L.push('', `Fill rules: declared \`${r.topology.declaredFillRule}\`; evenodd reproduces topology: ${r.topology.fillRules.evenodd.reproducesDeclaredTopology}; nonzero: ${r.topology.fillRules.nonzero.reproducesDeclaredTopology}.`);
    if (r.negativeSpace.counters.length) {
      L.push('', 'Counters: ' + r.negativeSpace.counters.map((c) => `\`${c.id}\` enclosed=${c.boundedFace}, area=${c.area}`).join('; '));
    }
    const ms = [...r.clearance.counterWalls.map((m) => ['counter wall', m]), ...r.clearance.boundarySelfProximity.map((m) => ['outer self-proximity', m])];
    if (ms.length) {
      L.push('', '| Measurement | Segments | Distance | ± bound | Side |', '|---|---|---|---|---|');
      for (const [kind, m] of ms) L.push(`| ${kind} | ${m.segmentIds.map(short).join(' ↔ ')} | ${m.minimumDistance} | ${m.measurementErrorBound} | ${m.side} |`);
    }
    L.push('', 'Identity checks:');
    for (const c of r.identityChecks) L.push(`- \`${c.name}\`: **${c.status}** — ${c.reason}`);
    const notable = r.diagnostics.filter((d) => d.severity !== 'info' || d.code.startsWith('GEO_'));
    if (notable.length) {
      L.push('', 'Diagnostics:');
      for (const d of notable) L.push(`- \`${d.code}\` (${d.severity}): ${d.message}`);
    }
  }
  const q = reports.find((x) => x.glyphId === 'latin.upper.Q');
  L.push('', '## Provisional findings', '');
  for (const d of q.diagnostics.filter((x) => x.severity === 'error')) {
    L.push(`- Q \`${d.code}\`: ${d.message} Segments: ${d.affectedIds.map(short).join(', ')}.`);
  }
  return L.join('\n') + '\n';
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const profile = JSON.parse(readFileSync(PROFILE_PATH, 'utf8'));
  const text = renderValidationReport(loadRegistry(), profile);
  if (process.argv.includes('--check')) {
    if (readFileSync(VALIDATION_REPORT_PATH, 'utf8') !== text) { console.error(`${VALIDATION_REPORT_PATH} is stale`); process.exit(1); }
    console.log('Report up to date.');
  } else {
    writeFileSync(VALIDATION_REPORT_PATH, text);
    console.log(`Wrote ${VALIDATION_REPORT_PATH}`);
  }
}
